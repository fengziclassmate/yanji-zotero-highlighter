const assert = require('node:assert/strict');
require('../yanji-edge/shared.js');
const Y = globalThis.Yanji;
assert.equal(Y.defaults.categories.length, 9);
assert.equal(Y.defaults.style, 'both');
assert.equal(Y.defaults.continuous, false);
assert.equal(Y.normalize('中文，保留全角标点：测试。'), '中文，保留全角标点：测试。');
assert.equal(Y.folderTitle('A: B? C/D\\E<F>G"H|I*J'), 'A B C D E F G H I J');
assert.equal(Y.folderTitle('Line\u0000one\r\ntwo\u001fend.  '), 'Line one two end');
assert.equal(Y.folderTitle('中文：标题？与“引号”，保留。'), '中文：标题？与“引号”，保留。');
assert.equal(Y.folderTitle('Title... '), 'Title');
assert.equal(Y.folderTitle('CON'), '_CON');
assert.equal(Y.folderTitle('nul.txt'), '_nul.txt');
assert.equal(Y.folderTitle('LPT³.data'), '_LPT³.data');
assert.equal(Y.folderTitle('conquest'), 'conquest');
assert.equal(Y.folderTitle('***...'), '未命名');
assert.equal(Y.folderTitle('长'.repeat(300)), '长'.repeat(300));
assert.equal(Y.doi('https://doi.org/10.1234/ABC'), '10.1234/abc');
assert.equal(Y.pageID({ doi: '10.1234/ABC', url: 'https://example.org' }), 'doi:10.1234/abc');
assert.equal(Y.cleanURL('https://example.org/p?id=2&utm_source=x#yanji=abc'), 'https://example.org/p?id=2');
const annotation = { id: 'example', url: 'https://example.org/p', title: '示例', quote: '<script>中文摘录</script>', category: 'content', comment: '<img src=x onerror=alert(1)>', createdAt: '2026-01-01', segments: [{ index: 1, heading: '局限性', translated: true, original: 'Original paragraph.' }] };
const managed = Y.renderManaged(Y.defaults, { title: '测试文献' }, [annotation]);
assert.ok(managed.includes('&lt;script&gt;'));
assert.ok(!managed.includes('<script>'));
assert.ok(!managed.includes('<img'));
assert.ok(managed.includes('原文段落'));
assert.ok(managed.includes('#yanji=example'));
assert.equal((managed.match(/<h2>Content<\/h2>/g) || []).length, 1);
const html = managed + `<h2>${Y.summaryTitle}</h2><p>手写总结</p>`;
assert.equal(Y.splitNote(html).manual, `<h2>${Y.summaryTitle}</h2><p>手写总结</p>`);
assert.throws(() => Y.splitNote('<p>missing marker</p>'));
assert.throws(() => Y.validateSettings({ ...Y.defaults, categories: [{ id: 'bad', name: 'bad', color: 'red;url(x)', meaning: '' }] }));
assert.throws(() => Y.validateSettings({ ...Y.defaults, defaultCategory: 'missing' }));
const captured = { ...annotation, comment: '', segments: [{ quote: '中文，摘录。', original: 'Original.', paragraphText: '中文，摘录。', heading: '', before: '', after: '', prefix: '', suffix: '', elementId: '', index: 0, translated: true }] };
assert.equal(Y.validateAnnotation(captured, new Set(['content'])), captured);
assert.throws(() => Y.validateAnnotation({ ...captured, segments: [{ quote: 123 }] }, new Set(['content'])));
assert.ok(Y.markdown({ title: '示例', url: annotation.url }, [annotation], Y.defaults).includes('## Content'));
const repeated = Array.from({length:30},(_,index)=>({...annotation,id:'repeat-'+index,quote:'中文摘录 '+index,comment:'批注 '+index,segments:[{...annotation.segments[0],original:'UNIQUE_LONG_PARAGRAPH '+ 'English text. '.repeat(3000)}]}));
const deduped = Y.planNote(Y.defaults,{title:'去重测试'},repeated);
assert.equal((deduped.html.match(/UNIQUE_LONG_PARAGRAPH/g)||[]).length,1);
assert.ok(deduped.html.includes('原文 P1'));
assert.equal(deduped.compacted,false);
const manySources = Array.from({length:300},(_,index)=>({...annotation,id:'unique-'+index,quote:'必须保留的中文 '+index,comment:'必须保留的批注 '+index,segments:[{...annotation.segments[0],original:`English paragraph ${index}. `+'source '.repeat(1200)}]}));
const compact = Y.planNote(Y.defaults,{title:'长度测试'},manySources,`<h2>${Y.summaryTitle}</h2><p>手写总结不能丢</p>`);
assert.equal(compact.compacted,true); assert.ok(compact.length<=Y.noteLimit);
for(const row of manySources) { assert.ok(compact.html.includes(row.quote)); assert.ok(compact.html.includes(row.comment)); }
assert.ok(compact.html.includes('手写总结不能丢'));
assert.throws(()=>Y.planNote(Y.defaults,{title:'过长'},[{...annotation,comment:'必须保留'.repeat(50000)}]),error=>error.code==='NOTE_TOO_LONG');
const aligned = {...annotation, quote:'第一句中文。第二句中文。', comment:'', segments:[{...captured.segments[0], quote:'第一句中文。第二句中文。', original:'First English sentence. Second English sentence. Unselected context.', sentencePairs:[{index:0,chinese:'第一句中文。',english:['First English sentence.']},{index:1,chinese:'第二句中文。',english:['First English sentence.','Second English sentence.']}]}]};
const alignedHTML = Y.planNote(Y.defaults,{title:'句对去重'},[aligned]).html;
assert.equal((alignedHTML.match(/第一句中文。/g)||[]).length,1);
assert.equal((alignedHTML.match(/First English sentence\./g)||[]).length,1);
assert.ok(!alignedHTML.includes('手动确认的句对'));
assert.ok(!alignedHTML.includes('Unselected context.'));
const partial = {...aligned,segments:[{...aligned.segments[0],sentencePairs:aligned.segments[0].sentencePairs.slice(0,1)}]};
assert.ok(!Y.planNote(Y.defaults,{title:'部分对齐'},[partial]).html.includes('Unselected context.'));
const alignedMD = Y.markdown({title:'句对去重',url:aligned.url},[aligned],Y.defaults);
assert.equal((alignedMD.match(/第一句中文。/g)||[]).length,1);
assert.equal((alignedMD.match(/First English sentence\./g)||[]).length,1);
assert.equal(Y.summaryTitle,'我的总结');
const legacy = '<h2 class="summary">我的总结（手写保留）</h2><p><strong>手写内容</strong>与链接保持原样。</p>';
assert.equal(Y.splitNote(managed+legacy).manual,legacy.replace('我的总结（手写保留）','我的总结'));
assert.equal(Y.splitNote(managed+legacy).legacyHeading,true);
console.log('PASS shared: defaults, DOI/URL identity, escaping, classification, manual preservation, settings validation, Markdown');
